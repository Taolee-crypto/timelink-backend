import assert from 'node:assert/strict';
import {runEscrowSimulation,createSim,reserve,settle,cancel} from '../src/v5-exchange-simulator.ts';
import {parseWholeTL,parseTLCAtoms,calculateTLCAtoms,validateQuoteExpiry} from '../src/v5-exchange-validation.ts';
const result=runEscrowSimulation();
for(const test of result.results)console.log((test.pass?'PASS':'FAIL')+' '+test.name);
assert.equal(result.total,10);
assert.equal(result.passed,10);
assert.equal(result.ok,true);
assert.equal(parseWholeTL('3600'),3600);
assert.throws(()=>parseWholeTL('1.5'));
assert.throws(()=>parseWholeTL('0'));
assert.equal(parseTLCAtoms('1.000000001'),1000000001n);
assert.throws(()=>parseTLCAtoms('1.0000000001'));
assert.equal(calculateTLCAtoms(3600,1000000000),3600000000000);
assert.throws(()=>calculateTLCAtoms(Number.MAX_SAFE_INTEGER,1000000000));
validateQuoteExpiry(new Date(Date.now()+60000).toISOString());
assert.throws(()=>validateQuoteExpiry(new Date(Date.now()-1000).toISOString()));
const s=createSim(50,100n);reserve(s,20,'r');assert.equal(cancel(s,'c'),true);assert.equal(s.walletTL,50);assert.throws(()=>settle(s,20n,'p'));
console.log('PASS: 10 escrow scenarios and 11 exact-amount/quote assertions');
