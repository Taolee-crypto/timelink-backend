'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {buildSync}=require('esbuild');
const built=buildSync({entryPoints:[path.join(__dirname,'../src/tilo-v5-station-operations.ts')],
 bundle:true,platform:'node',format:'cjs',target:'node22',write:false});
const moduleObj={exports:{}};
new Function('module','exports',built.outputFiles[0].text)(moduleObj,moduleObj.exports);
const {classifyTiloStationOperation:status,isTiloStreamVerified}=moduleObj.exports;
const now=Date.parse('2026-10-31T09:00:00.000Z');
const baseline={serviceEnabled:true,receiverTracks:23,licensedTracks:5,lastVerifiedEndAt:'2026-10-31T08:59:30Z',nowMs:now};
assert.equal(status(baseline),'VERIFIED_AIRTIME_RECENT');
assert.equal(status({...baseline,serviceEnabled:false}),'SERVICE_DISABLED');
assert.equal(status({...baseline,licensedTracks:0}),'NO_COUNTRY_RIGHTS');
assert.equal(status({...baseline,receiverTracks:0}),'NO_RECEIVER_TRACKS');
assert.equal(status({...baseline,lastVerifiedEndAt:null}),'NO_VERIFIED_AIRTIME');
assert.equal(status({...baseline,lastVerifiedEndAt:'2026-10-31T08:45:00Z'}),'VERIFIED_AIRTIME_STALE');
assert.equal(status({...baseline,lastVerifiedEndAt:'invalid'}),'VERIFIED_AIRTIME_STALE');
assert.equal(isTiloStreamVerified({lastVerifiedEndAt:baseline.lastVerifiedEndAt}),false);
const route=fs.readFileSync(path.join(__dirname,'../src/routes/admin.ts'),'utf8');
const begin=route.indexOf("router.get('/central-broadcast/operations'");
assert.ok(begin>0,'missing admin TILO operations route');
const end=route.indexOf("router.get('/cafe/channels'",begin);
assert.ok(end>begin);
const section=route.slice(begin,end);
assert.match(section,/requireAdmin\(c\)/);
assert.match(section,/central_broadcast_rights_grants/);
assert.match(section,/central_broadcast_service_file_grants/);
assert.match(section,/tilo_v5_verified_airtime/);
assert.match(section,/tilo_v5_settlement_approvals/);
assert.match(section,/server_audio_stream:false/);
assert.doesNotMatch(section,/postLedgerTransaction|INSERT\s+INTO|UPDATE\s+|DELETE\s+|CREATE\s+TABLE/i);
assert.match(section,/BROADCAST_SERVICE_CREDENTIAL_MISSING/);
assert.match(section,/INDEPENDENT_AUDIO_PLAYOUT_NOT_VERIFIED/);
assert.match(section,/broadcaster_credential_configured/);
assert.match(section,/broadcast_runtime_ready:false/);
assert.match(section,/const licensedTracks=receiverTracks/);
assert.doesNotMatch(section,/console\.log\([^\n]*CENTRAL_BROADCAST_WORKER_SECRET/);
console.log('PASS TILO operations: admin-only read path, rights evidence settlement truth and no synthetic stream');
