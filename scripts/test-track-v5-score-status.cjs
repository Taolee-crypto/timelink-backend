'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'../src/routes/score.ts'),'utf8');
const start=src.indexOf('/** Owner-only V5 transcriptions.');
const end=src.indexOf("// ─────────────────────────────────────────\n// DB 마이그레이션",start);
assert.ok(start>0&&end>start,'V5 song-based score route exists');
const body=src.slice(start,end);
assert.match(body,/tl3_v5_releases/,'V5 only');
assert.match(body,/v\.file_id=\?/,'numeric TRACK file ID maps to V5');
assert.match(body,/v\.share_id=\?/,'V5 share ID maps to V5');
assert.match(body,/f\.shared=1/,'only public shared files');
assert.match(body,/COALESCE\(f\.revenue_held,0\)=0/,'no held content exposed');
assert.match(body,/score_status:score\?'draft':'not_generated'/);
assert.match(body,/has_score:!!score/);
assert.match(body,/tld_issued:false/);
assert.match(body,/tl_charged:0/);
assert.ok(!body.includes('tl3_releases'),'do not query legacy V3');
assert.ok(!body.includes('UPDATE users'),'no wallet mutation');
assert.ok(!body.includes('score_uses'),'no legacy purchase');
assert.ok(!body.includes('/score.timelink.digital'),'no TLD proxy');
console.log('PASS TRACK V5 score status: sealed asset, no legacy 404, no TLD issuance or TL charge');
