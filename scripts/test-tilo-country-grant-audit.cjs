'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const source=fs.readFileSync('src/routes/admin.ts','utf8');
const start=source.indexOf("router.get('/central-broadcast/stations/:country/audit'");
const end=source.indexOf("router.get('/central-broadcast/stations/:country',",start);
assert.ok(start>0&&end>start);
const audit=source.slice(start,end);
assert.match(audit,/requireAdmin\(c\)/);
assert.match(audit,/country_broadcast_rights/);
assert.match(audit,/central_broadcast_service_file_grants/);
assert.match(audit,/service_granted/);
assert.match(audit,/rights_blocked/);
assert.match(audit,/owner_user_id/);
assert.match(audit,/Number\(r\.owner_user_id\)===adminId/);
assert.match(audit,/can_grant:!!canGrant/);
assert.match(audit,/COUNTRY_SERVICE_GRANT_MISSING/);
assert.match(audit,/BROADCAST_RIGHTS_BLOCKED/);
assert.match(audit,/REVENUE_HOLD/);
const grantStart=source.indexOf("router.post('/central-broadcast/stations/:country/grants'");
assert.ok(grantStart>0&&grantStart<start);
const grant=source.slice(grantStart,start);
assert.match(grant,/v\.user_id=\?/);
assert.match(grant,/BROADCAST_RIGHTS_NOT_CLEARED/);
assert.match(grant,/requireAdmin\(c\)/);
console.log('PASS TILO country grant audit: owner-only review, revocations and authorized-service gate');
